#!/usr/bin/env python3
"""Analytical error bounds for the ProvGuard Causal Gate (Theorem 2).

Not an experiment: every number is computed exactly from the binomial
distribution or from the Hoeffding / Chernoff-KL bounds stated in the paper.
Outputs:
  figures/data_gate_bounds.dat   (curves for Fig. gate bounds)
  sections/table_min_trials.tex  (Table: minimum k)
"""
import math, os

def tail_ge(k, q, m):
    """P[Bin(k,q) >= m]."""
    return sum(math.comb(k, j) * q**j * (1 - q)**(k - j) for j in range(max(m, 0), k + 1))

def pass_prob(k, q, th):
    """Probability that the gate passes: P[hat p >= th] with hat p = Bin(k,q)/k."""
    return tail_ge(k, q, math.ceil(th * k - 1e-12))

def kl(a, b):
    return a * math.log(a / b) + (1 - a) * math.log((1 - a) / (1 - b))

def min_k_exact(q0, q1, th, d):
    for k in range(1, 5000):
        if pass_prob(k, q0, th) <= d and 1 - pass_prob(k, q1, th) <= d:
            return k

def min_k_hoeffding(q0, q1, th, d):
    return math.ceil(max(math.log(1/d) / (2*(th-q0)**2), math.log(1/d) / (2*(q1-th)**2)))

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(root, 'figures', 'data_gate_bounds.dat'), 'w') as f:
    f.write("% Analytical values (not experimental). Generated by scripts/gate_bounds.py; theta = 0.5\n")
    f.write("k exfp hffp chfp exfn hffn exfp3 hffp3\n")
    for k in range(1, 41):
        row = (k, pass_prob(k, .2, .5), math.exp(-2*k*.3**2), math.exp(-k*kl(.5, .2)),
               1 - pass_prob(k, .8, .5), math.exp(-2*k*.3**2),
               pass_prob(k, .3, .5), math.exp(-2*k*.2**2))
        f.write(" ".join(f"{v:.6g}" for v in row) + "\n")

pairs = [(0.1, 0.9), (0.2, 0.8), (0.3, 0.7), (0.1, 0.6), (0.4, 0.9)]
deltas = [0.05, 0.01, 0.001]
with open(os.path.join(root, 'sections', 'table_min_trials.tex'), 'w') as f:
    f.write("% Generated by scripts/gate_bounds.py (analytical, not experimental)\n")
    for q0, q1 in pairs:
        th = (q0 + q1) / 2
        cells = []
        for d in deltas:
            cells.append(f"{min_k_exact(q0,q1,th,d)} & {min_k_hoeffding(q0,q1,th,d)}")
        f.write(f"{q0:.1f} & {q1:.1f} & {th:.2f} & " + " & ".join(cells) + " \\\\\n")
print("ok")
