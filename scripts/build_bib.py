#!/usr/bin/env python3
"""Assemble references_verified.bib from the per-cluster verified bibs.
Only entries that are actually cited in the manuscript are emitted; entries
are grouped into the six categories required by the citation protocol."""
import re, glob, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def parse(path):
    s = open(path).read(); out = {}; i = 0
    while True:
        m = re.search(r'@(\w+)\s*\{\s*([^,\s]+)\s*,', s[i:])
        if not m: break
        start = i + m.start(); j = i + m.end(); depth = 1
        while depth and j < len(s):
            if s[j] == '{': depth += 1
            elif s[j] == '}': depth -= 1
            j += 1
        out[m.group(2)] = s[start:j]; i = j
    return out
entries = {}
for f in ['litA.bib', 'litB.bib', 'litC.bib', 'litD.bib', 'litE_extra.bib']:
    for k, v in parse(os.path.join(root, 'audit', f)).items():
        if k in entries: print('dup', k, file=sys.stderr); continue
        entries[k] = v
tex = ''
for f in glob.glob(os.path.join(root, '**', '*.tex'), recursive=True):
    tex += open(f).read()
cited = set()
for m in re.finditer(r'\\cite[pt]?\*?(?:\[[^\]]*\])?\{([^}]*)\}', tex):
    cited.update(k.strip() for k in m.group(1).split(','))
missing = sorted(cited - set(entries))
cats = [
 ('1. Core seed references from the idea document', ['deivasigamani2026nota11y','chen2026mobileworldsafety','li2026uidesync','liu2026agenthazard','liu2025hijackingjarvis','du2025measuringmobileagents','qian2026zeropermission','xu2026pusv','liu2026visualconfuseddeputy','chen2025ghosteibench','sun2026ossentinel','zou2026aura','zhao2026aohp','debenedetti2025camel','costa2025fides','siddiqui2025permissive','cai2026neurotaint','shim2026flowseal','kravchenko2026appa','zhu2025melon','li2026ace','wu2025isolategpt','hines2024spotlighting','enck2010taintdroid','enck2014taintdroid','pasquier2017camflow','fratantonio2017cloak','yan2019overlay','rawles2025androidworld','xu2025androidlab','ye2025mobileagentv3','droidrun2025software','liu2024autoglm','openautoglm2025software','qin2025uitars']),
 ('2. Closest competing methods (defenses and detectors)', ['shi2025progent','chen2025struq','chen2025secalign','wallace2024instruction','liu2024formalizing','wen2024autodroid']),
 ('3. Foundational theory', ['denning1976lattice','biba1977integrity','goguen1982noninterference','sabelfeld2003language','myers1997decentralized','myers2000dlm','krohn2007flume','pearl2009causality','hardy1988confused','bishop1996toctou']),
 ('4. System, platform, and UI-security background', ['jang2014a11y','bianchi2015whattheapp','fernandes2016uideception','huang2012clickjacking','felt2011redelegation','kalysch2018a11y','naseri2019accessileaks','android12_untrusted_touch','android15_otp_redaction','android_blog_a11y_sensitive','android_accessibilityserviceinfo','android_accessibilitynodeinfo','android_accessibilitywindowinfo','android_sdkruntime','android_surfaceflinger','android_appfunctions','wcag21','sundararajan2017axiomatic','abnar2020attentionflow','jain2019attention']),
 ('5. Experimental baselines, benchmarks, and agents', ['greshake2023notwhat','zhan2024injecagent','debenedetti2024agentdojo','liao2025eia','zhang2025popups','ma2025caution','evtimov2025wasp','wu2025dissecting','chen2025fineprint','rawles2023aitw','chen2025spabench','wang2024mobileagent','wang2024mobileagentv2','zhang2025appagent','wen2025autodroidv2','hong2024cogagent','cheng2024seeclick','wu2025osatlas']),
 ('6. Peripheral context references', ['zhang2025llmbrainedguiagents','shi2025trustworthyguiagents','tian2026agentprog','google2026gemininano']),
]
placed = set(); out = ['% references_verified.bib -- ProvGuard manuscript',
 '% Generated by scripts/build_bib.py from audit/litA..litD.bib and audit/litE_extra.bib.',
 '% Every entry was verified against the source listed in citation_claim_map.csv on 2026-10-03.',
 '% Only entries cited in the manuscript are included.', '']
for title, keys in cats:
    out.append('% ' + '=' * 68); out.append('% ' + title); out.append('% ' + '=' * 68)
    for k in keys:
        if k in cited and k in entries:
            out.append(entries[k].strip()); out.append(''); placed.add(k)
rest = sorted(cited - placed - set(missing))
if rest:
    out.append('% ' + '=' * 68); out.append('% Other cited (uncategorized)'); out.append('% ' + '=' * 68)
    for k in rest: out.append(entries[k].strip()); out.append('')
open(os.path.join(root, 'references_verified.bib'), 'w').write('\n'.join(out))
print('cited', len(cited), 'emitted', len(placed) + len(rest), 'missing', missing, 'uncategorized', rest)
unused = sorted(set(entries) - cited)
open(os.path.join(root, 'audit', 'verified_but_unused.txt'), 'w').write('\n'.join(unused))
print('verified but unused:', len(unused))
