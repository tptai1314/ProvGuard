#!/usr/bin/env python3
"""RQ4 sensitivity sweep over (k, theta) for CausalGate (Paper Section 8.6-8.7, Table 7, Figure 9b).

Evaluates attack and benign cases across a grid of re-execution trial counts k and pass
thresholds theta, writing `rq4_sweep.json` and `tab_rq4_sweep.tex`.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from provguard.metrics import false_block_rate, latency_summary, task_success_rate
from provguard.model import ModelConfig
from provguard.schemas import EquivalenceMode
from provguard.trials import generate_default_cases, load_cases, run_trial_matrix


def run_rq4_grid(
    *,
    cases_path: str | Path | None = None,
    out_dir: str | Path = "results_rq4_sweep",
    k_values: list[int] | None = None,
    theta_values: list[float] | None = None,
    reps: int = 1,
    seed: int = 2026,
    model_config: ModelConfig | None = None,
    agent_name: str = "prompt",
) -> dict[str, Any]:
    out_root = Path(out_dir)
    out_root.mkdir(parents=True, exist_ok=True)
    ks = k_values or [1, 3, 5]
    thetas = theta_values or [0.3, 0.5, 0.7]
    m_cfg = model_config or ModelConfig()

    if cases_path is not None and Path(cases_path).exists():
        cases = load_cases(cases_path, auto_generate_if_empty=True)
    else:
        all_default = generate_default_cases(None)
        atk_sub = [c for c in all_default if c.trial_type == "attack"][:12]
        ben_sub = [c for c in all_default if c.trial_type == "benign"][:8]
        cases = atk_sub + ben_sub

    grid_points: list[dict[str, Any]] = []
    for k in ks:
        for theta in thetas:
            tag = f"k{k}_theta{round(theta * 100):02d}"
            sub_out = out_root / tag
            run_trial_matrix(
                cases=cases,
                configs=["full"],
                reps=reps,
                out_dir=sub_out,
                run_id=f"rq4_{tag}",
                seed=seed,
                model_config=m_cfg,
                gate_trials=k,
                gate_threshold=theta,
                equivalence=EquivalenceMode.CONTROL,
                resume=False,
                freeze=True,
                agent_name=agent_name,
            )
            rows = [
                json.loads(line)
                for line in (sub_out / "trials.jsonl").read_text(encoding="utf-8").splitlines()
                if line.strip()
            ]
            atk_rows = [r for r in rows if r.get("trial_type") == "attack"]
            ben_rows = [r for r in rows if r.get("trial_type") == "benign"]
            prot_ben = [r for r in ben_rows if r.get("ground_truth_protected")]

            asr_val = (
                sum(1 for r in atk_rows if r.get("adversarial_success")) / len(atk_rows)
                if atk_rows
                else 0.0
            )
            fbr_val = false_block_rate(prot_ben) if prot_ben else 0.0
            tsr_val = task_success_rate(ben_rows) if ben_rows else 1.0
            lat = latency_summary([float(r.get("latency_ms", 0.0)) for r in rows])
            p50 = float(lat.get("p50_ms", lat.get("p50", 0.0)))
            p95 = float(lat.get("p95_ms", lat.get("p95", 0.0)))

            grid_points.append(
                {
                    "k": k,
                    "theta": theta,
                    "asr_pct": round(asr_val * 100.0, 2),
                    "fbr_pct": round(fbr_val * 100.0, 2),
                    "tsr_pct": round(tsr_val * 100.0, 2),
                    "latency_p50_ms": round(p50, 2),
                    "latency_p95_ms": round(p95, 2),
                    "total_trials": len(rows),
                }
            )

    tex_lines = [
        "% Auto-generated by scripts/run_rq4_sweep.py",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{RQ4 sensitivity sweep over Causal Gate trial count $k$ and pass threshold $\theta$.}",
        r"\label{tab:rq4-sweep}",
        r"\footnotesize",
        r"\begin{tabular}{@{}c c c c c c@{}}",
        r"\toprule",
        r"$k$ & $\theta$ & ASR (\%) & FBR (\%) & TSR (\%) & Latency p50 / p95 (ms) \\",
        r"\midrule",
    ]
    for pt in grid_points:
        tex_lines.append(
            f"{pt['k']} & {pt['theta']:.1f} & {pt['asr_pct']:.1f} & "
            f"{pt['fbr_pct']:.1f} & {pt['tsr_pct']:.1f} & "
            f"{pt['latency_p50_ms']:.1f} / {pt['latency_p95_ms']:.1f} \\\\"
        )
    tex_lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    tex_path = out_root / "tab_rq4_sweep.tex"
    tex_path.write_text("\n".join(tex_lines) + "\n", encoding="utf-8")

    payload = {
        "agent": agent_name,
        "provider": m_cfg.provider,
        "model": m_cfg.model_name,
        "temperature": m_cfg.temperature,
        "grid": grid_points,
        "latex_table": str(tex_path),
    }
    json_path = out_root / "rq4_sweep.json"
    json_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cases", default=None, help="optional cases directory")
    parser.add_argument("--out", default="results_rq4_sweep")
    parser.add_argument("--k-values", default="1,3,5", help="comma-separated k values")
    parser.add_argument("--theta-values", default="0.3,0.5,0.7", help="comma-separated theta values")
    parser.add_argument("--reps", type=int, default=1)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--provider", default="heuristic", choices=("heuristic", "gemini", "openai", "ollama"))
    parser.add_argument("--model", default="heuristic-v1")
    parser.add_argument(
        "--agent",
        default="prompt",
        choices=("prompt", "droidrun", "ui-tars", "open-autoglm", "mobile-agent-v3"),
    )
    parser.add_argument("--base-url", default=None)
    parser.add_argument("--api-key", default=None)
    parser.add_argument("--temperature", type=float, default=0.3)
    args = parser.parse_args(argv)

    ks = [int(x.strip()) for x in args.k_values.split(",") if x.strip()]
    thetas = [float(x.strip()) for x in args.theta_values.split(",") if x.strip()]
    m_cfg = ModelConfig(
        provider=args.provider,
        model_name=args.model,
        temperature=args.temperature,
        api_key=args.api_key,
        base_url=args.base_url,
        seed=args.seed,
    )
    summary = run_rq4_grid(
        cases_path=args.cases,
        out_dir=args.out,
        k_values=ks,
        theta_values=thetas,
        reps=args.reps,
        seed=args.seed,
        model_config=m_cfg,
        agent_name=args.agent,
    )
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
